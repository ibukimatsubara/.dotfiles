local module_path = ... or (os.getenv("HOME") .. "/.hammerspoon/kensington_swap.so")
local open_module = assert(package.loadlib(module_path, "luaopen_kensington_swap"))
local swap = open_module()
assert(not swap:status().running, "module starts stopped")
local function cleanup_on_error(message)
  swap:stop()
  return debug.traceback(message, 2)
end
local ok, result = xpcall(function()
  assert(swap:start(true))
  assert(swap:status().running and swap:status().listenOnly, "observer starts without changing input")
  assert(swap:start(true))
  assert(swap:status().running, "repeated observer start is safe")
  local changed, err = swap:start(false)
  assert(not changed and type(err) == "string", "mode change requires stop first")
  assert(swap:status().listenOnly, "failed mode change preserves observer")
  swap:stop()
  assert(not swap:status().running, "stop disables observer")
  swap:stop()
  assert(not swap:status().running, "repeated stop is safe")
  assert(swap:start(true))
  assert(swap:status().running, "observer restarts after stop")
  local other = open_module()
  assert(other:start(true))
  other:stop()
  assert(swap:status().running, "independent object stop preserves original observer")
  swap:stop()
  return "PASS Kensington lifecycle: observer start, repeated start/stop, restart and independent owners"
end, cleanup_on_error)
assert(ok, result)
return result
