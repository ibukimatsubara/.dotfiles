#!/usr/bin/env bash
set -euo pipefail
DOTFILES_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
source "$DOTFILES_ROOT/platforms/common/lib.sh"
source "$DOTFILES_ROOT/platforms/common/setup.sh"
if [ "$(detect_platform)" != ubuntu ]; then
    print_error 'This desktop profile requires Ubuntu.'
    exit 1
fi
if ! Hyprland --version | grep -Eq 'Hyprland 0\.53\.'; then
    print_error 'This profile targets Hyprland 0.53.x. Review the config before using another series.'
    exit 1
fi
config_dir="${XDG_CONFIG_HOME:-$HOME/.config}"
mkdir -p "${XDG_DATA_HOME:-$HOME/.local/share}/vicinae/themes"
mkdir -p "$config_dir/hypr" "$config_dir/DankMaterialShell" "$config_dir/fcitx5" "$config_dir/systemd/user" "$config_dir/vicinae"
generated_dir="$config_dir/dotfiles/hypr"
mkdir -p "$generated_dir"
if [ ! -e "$generated_dir/theme.conf" ]; then
    printf '# Theme colors are published by ubuntu-theme.py apply.\n' > "$generated_dir/theme.conf"
fi
temp_config="$(mktemp "$generated_dir/hyprland.conf.XXXXXX")"
printf '# Generated by setup-desktop.sh. Edit the repository config or local.conf.\nsource = %s\nsource = %s\nsource = %s\n' \
    "$DOTFILES_ROOT/platforms/ubuntu/hypr/hyprland.conf" "$generated_dir/theme.conf" "$config_dir/hypr/local.conf" > "$temp_config"
if [ -f "$generated_dir/hyprland.conf" ] && cmp -s "$temp_config" "$generated_dir/hyprland.conf"; then
    rm -f "$temp_config"
else
    mv "$temp_config" "$generated_dir/hyprland.conf"
fi
link_managed_path "$generated_dir/hyprland.conf" "$config_dir/hypr/hyprland.conf"
for name in hypridle.conf hyprlock.conf; do
    link_managed_path "$DOTFILES_ROOT/platforms/ubuntu/hypr/$name" "$config_dir/hypr/$name"
done
if [ ! -e "$config_dir/hypr/local.conf" ]; then
    printf '# Machine-local monitor, keyboard, and window overrides.\n' > "$config_dir/hypr/local.conf"
fi
# DMS writes its own settings: seed once instead of symlinking tracked JSON.
if [ ! -e "$config_dir/DankMaterialShell/settings.json" ]; then
    cp "$DOTFILES_ROOT/platforms/ubuntu/dms/settings.json" "$config_dir/DankMaterialShell/settings.json"
fi
for seed in dms/clsettings.json vicinae/vicinae.json; do
    case "$seed" in
        dms/*) target="$config_dir/DankMaterialShell/${seed#*/}" ;;
        *) target="$config_dir/$seed" ;;
    esac
    if [ ! -e "$target" ]; then
        cp "$DOTFILES_ROOT/platforms/ubuntu/$seed" "$target"
    fi
done
if [ ! -e "$config_dir/fcitx5/profile" ]; then
    cp "$DOTFILES_ROOT/platforms/ubuntu/fcitx5/profile" "$config_dir/fcitx5/profile"
fi
# Mutable local preferences are seeded once; plugin source stays managed.
for name in break-timer mic-priority; do
    if [ ! -e "$config_dir/dotfiles/$name.json" ]; then
        cp "$DOTFILES_ROOT/platforms/ubuntu/$name.json" "$config_dir/dotfiles/$name.json"
    fi
done
mkdir -p "$config_dir/DankMaterialShell/plugins"
for name in dotfilesBreakTimer dotfilesCodexUsage; do
    link_managed_path "$DOTFILES_ROOT/platforms/ubuntu/dms/plugins/$name" "$config_dir/DankMaterialShell/plugins/$name"
done
python3 "$DOTFILES_ROOT/scripts/ubuntu-desktop-preferences.py"
# Prefer the distro-integrated Code package over an older user-local tarball.
if [ -x /usr/bin/code ] && [ -L "$HOME/.local/bin/code" ]; then
    case "$(readlink -f "$HOME/.local/bin/code")" in
        "$HOME"/.local/opt/VSCode-linux-*/bin/code)
            link_managed_path /usr/bin/code "$HOME/.local/bin/code" ;;
    esac
fi
python3 "$DOTFILES_ROOT/scripts/ubuntu-app-desktop.py"
# The DMS package enables a global graphical-session unit. Start it only from
# our Hyprland session supervisor, never automatically on a GNOME login.
link_managed_path /dev/null "$config_dir/systemd/user/dms.service"
print_success 'Hyprland + DMS profile linked. Existing DMS preferences and local.conf are preserved.'
print_info 'Select Hyprland from the login screen when ready. GNOME remains available.'
